// デプロイ環境ごとに書き換える設定。ビルド工程が無いので、この値を直接編集して使う。
//
// このファイルはそのまま配信される。書いた内容は閲覧者から見えるので、
// 秘密にすべき値を置かないこと。
(function registerConfig(globalObject) {
	// ------------------------------------------------------------------
	// googleDriveApiKey
	//
	// Googleドライブの共有リンクを読み込むためのGoogle Cloud APIキー。
	//
	// 空文字のままでも構わない。その場合はGoogleドライブのリンクだけが
	// 理由を添えて拒否され、他の置き場所（GitHub / Dropbox / OneDrive /
	// CORS許可済みのサーバー）と埋め込みモードの共有はすべて動く。
	//
	// ■ なぜキーが必要か
	//
	// Googleドライブの共有URL（drive.google.com）はCORSヘッダーを返さないため、
	// ブラウザから直接は取得できない。Drive API（www.googleapis.com）はCORSを
	// 返すので、そちら経由なら読める。ただしAPIキーが要る。
	//
	// ■ 取得手順（Google Cloudコンソール）
	//
	// 課金アカウントの登録は不要。所要10分程度。
	//
	//   1. https://console.cloud.google.com/ にログインする。
	//      「無料トライアルを開始」「請求先アカウントを設定」の案内は無視してよい。
	//
	//   2. プロジェクトを作る。
	//      画面最上部のプロジェクト選択ドロップダウン →「新しいプロジェクト」→
	//      名前を付けて「作成」。組織は「組織なし」のままでよい。
	//      作成後、もう一度ドロップダウンを開いて作ったプロジェクトを選び直すこと。
	//      画面は自動で切り替わらない。ここで選び忘れると別プロジェクトへ設定してしまい、
	//      「設定したのに動かない」の原因になる。
	//
	//   3. Drive APIを有効化する。
	//      左上の ≡ →「APIとサービス」→「ライブラリ」→ "Google Drive API" を検索 →
	//      「有効にする」。ボタンが「管理」に変われば完了。
	//
	//   4. APIキーを作る。
	//      ≡ →「APIとサービス」→「認証情報」→「+ 認証情報を作成」→「APIキー」。
	//      この時点のキーは無制限なので、続けて手順5を必ず行う。
	//
	//   5. キーに制限をかける（最重要）。
	//      ダイアログの「キーを制限」、または認証情報一覧の鉛筆アイコンから:
	//
	//        - 名前:「MITO (mito.bblab.org)」など、後で用途が分かるもの
	//
	//        - アプリケーションの制限 →「ウェブサイト」を選ぶ
	//          （コンソールの版によっては「HTTPリファラー（ウェブサイト）」）
	//          →「追加」→ 配信元を登録する。mito.bblab.org なら
	//
	//               https://mito.bblab.org/*
	//
	//          末尾の /* を省くと、トップページ以外で弾かれる。
	//
	//        - APIの制限 →「キーを制限」→「Google Drive API」だけを選ぶ
	//
	//        - 「保存」。反映まで最大5分ほどかかる。直後に失敗しても少し待つ。
	//
	//   6. 下の googleDriveApiKey に貼り付け、配信する。
	//
	// ■ 公開してよいのか
	//
	// キーは配信ファイルに書かれる以上、閲覧者からは必ず見える。
	// 守っているのはキーの秘匿ではなく手順5のリファラー制限なので、
	// 制限をかけないまま公開しないこと。
	// 制限が効いていれば、他サイトからの利用も、curl等のリファラーを持たない
	// 直接のリクエストも、いずれも403で弾かれる（実測で確認済み）。
	//
	// 公開リポジトリへコミットすると、GitHubのシークレットスキャンが警告を出すことがある。
	// この設計では想定内なので、警告は閉じてよい。
	//
	// ■ 共有する側がやること
	//
	// キーが認可するのはアプリからのAPI利用であって、ファイルへのアクセス権ではない。
	// 読めるのは「リンクを知っている全員」に設定されたファイルだけ。
	// 共有する人はドライブ上でファイルを右クリック →「共有」→
	// 「一般的なアクセス」を「リンクを知っている全員」（閲覧者）に変更する。
	//
	// ■ 動かないとき
	//
	//   HTTP 404 … ファイルIDが違うか、ファイルが「リンクを知っている全員」に
	//              なっていない。Driveは非公開ファイルにも404を返すため、
	//              存在しない場合と区別がつかない。
	//   HTTP 403 … キーが拒否されている。リファラー制限の登録内容、APIの制限、
	//              利用量の上限を確認する。
	//
	// リファラー制限は配信元のドメインに紐づく。手元で index.html を直接開いたり
	// localhost で配信した場合、Googleドライブ経由の読み込みは403になる。これは正常。
	// 手元でも試したい場合は、リファラー制限に http://localhost:*/* を足しておく。
	// 他の置き場所と埋め込みモードは、この制限の影響を受けない。
	// ------------------------------------------------------------------
	/** @type {any} */ (globalObject).MITO_CONFIG = {
		googleDriveApiKey: "AIzaSyCvHPX2M3H2tqXF83Hawz29Vi0D7whGTJM",
	};
})(window);
